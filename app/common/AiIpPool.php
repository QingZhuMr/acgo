    /** 全部省份列表 */
    public static function provinces(): array
    {
        return array_keys(self::POOL);
    }

    /**
     * 随机生成一个国内公网 IP
     *
     * @param string $province 指定省份（可选；不指定则随机抽省，再随机抽该省段）
     * @return array{ip:string, location:string} ip 可能为空串（极端失败）
     */
    public static function random(string $province = ''): array
    {
        $province = trim($province);
        if ($province !== '' && !isset(self::POOL[$province])) {
            $province = '';
        }
        if ($province === '') {
            $provinces = array_keys(self::POOL);
            $province = $provinces[random_int(0, count($provinces) - 1)];
        }

        $cidrs = self::POOL[$province];
        $cidr  = $cidrs[random_int(0, count($cidrs) - 1)];
        $parts = explode('/', $cidr);
        $prefix = (int) ($parts[1] ?? 0);

        $net = ip2long($parts[0]);
        if (false === $net) {
            return ['ip' => '', 'location' => $province];
        }

        // 段内可用公网地址随机取一个（避开网络号/广播号）
        if ($prefix >= 31) {
            $start = $end = $net;
        } else {
            $mask      = 0xFFFFFFFF & (0xFFFFFFFF << (32 - $prefix));
            $network   = $net & $mask;
            $broadcast = $network | (0xFFFFFFFF ^ $mask);
            $start     = $network + 1;
            $end       = $broadcast - 1;
            if ($end <= $start) {
                $end = $start + 1;
            }
        }

        try {
            $ipLong = random_int($start, $end);
        } catch (\Throwable $e) {
            return ['ip' => '', 'location' => $province];
        }

        return ['ip' => long2ip($ipLong), 'location' => $province];
    }
